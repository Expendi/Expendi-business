/**
 * Seeds October and the page's default month (last month by the clock), so
 * the preview opens on the mock's figures whatever today is.
 */
export function seedReports(client: QueryClient): void {
  const org = ORGANIZATION_ID;
  const months = new Set([
    REPORT_MONTH,
    shiftMonth(nairobiMonth(new Date()), -1),
  ]);
  for (const month of months) {
    const shift = <T extends { month: string }>(data: T): T => ({
      ...data,
      month,
    });
    client.setQueryData(
      reportKeys.spending(org, month, 6),
      shift(REPORT_SPENDING_6),
    );
    client.setQueryData(
      reportKeys.spending(org, month, 12),
      shift(REPORT_SPENDING_12),
    );
    client.setQueryData(reportKeys.summary(org, month), shift(REPORT_SUMMARY));
  }
  client.setQueryData(reportKeys.exports(org), SHARED_EXPORTS);
}
